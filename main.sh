#!/bin/sh

# ==============================================================================
# cable2m3u
#
# 广电 IPTV API → M3U
#
# 执行：
#   sh main.sh
#
# Cron：
#   */30 * * * * /root/gcable2m3u/main.sh >/dev/null 2>&1
#
# ==============================================================================

# ==============================================================================
# 项目目录
# ==============================================================================

PROJECT_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)

# ==============================================================================
# 加载配置
# ==============================================================================

. "$PROJECT_DIR/config.sh"

# ==============================================================================
# 加载模块
# ==============================================================================

. "$PROJECT_DIR/model/source.sh"
. "$PROJECT_DIR/model/channel.sh"
. "$PROJECT_DIR/api/client.sh"
. "$PROJECT_DIR/transform/normalize.sh"
. "$PROJECT_DIR/output/m3u.sh"

# ==============================================================================
# 初始化
# ==============================================================================

init_runtime() {
    mkdir -p "$RUNTIME_DIR" || {
        echo "无法创建运行目录: $RUNTIME_DIR" >&2
        return 1
    }

    mkdir -p "$WEB_DIR" || {
        echo "无法创建 Web 目录: $WEB_DIR" >&2
        return 1
    }
}

# ==============================================================================
# 检查依赖
# ==============================================================================

check_dependencies() {
    [ -n "$API_CLIENT" ] || {
        echo "未配置 API_CLIENT，请在 gcable2m3u.config 或环境变量中设置" >&2
        return 1
    }

    command -v curl >/dev/null 2>&1 || {
        echo "缺少依赖: curl" >&2
        return 1
    }

    command -v jq >/dev/null 2>&1 || {
        echo "缺少依赖: jq" >&2
        return 1
    }
}

# ==============================================================================
# Web 软链接
# ==============================================================================

setup_web_links() {
    if [ -e "$WEB_DIR/iptv.m3u" ] || [ -L "$WEB_DIR/iptv.m3u" ]; then
        [ -L "$WEB_DIR/iptv.m3u" ] || {
            echo "Web 路径已存在但不是软链接: $WEB_DIR/iptv.m3u" >&2
            return 1
        }
    else
        ln -s "$M3U_FILE" "$WEB_DIR/iptv.m3u" || {
            echo "创建 M3U 软链接失败" >&2
            return 1
        }
    fi

    if [ -e "$WEB_DIR/epg.xml" ] || [ -L "$WEB_DIR/epg.xml" ]; then
        [ -L "$WEB_DIR/epg.xml" ] || {
            echo "Web 路径已存在但不是软链接: $WEB_DIR/epg.xml" >&2
            return 1
        }
    else
        ln -s "$EPG_FILE" "$WEB_DIR/epg.xml" || {
            echo "创建 EPG 软链接失败" >&2
            return 1
        }
    fi
}

# ==============================================================================
# 生成 M3U
# ==============================================================================

generate_m3u() {
    echo "正在生成 M3U..."

    # 先写临时文件。
    m3u_temp_file="$M3U_TEMP_FILE.$$"

    m3u_generate > "$m3u_temp_file" || {
        echo "M3U 生成失败" >&2
        rm -f "$m3u_temp_file"
        return 1
    }

    # 至少应该包含 #EXTM3U。
    [ -s "$m3u_temp_file" ] || {
        echo "M3U 文件为空" >&2
        rm -f "$m3u_temp_file"
        return 1
    }

    # 至少存在一个频道。
    m3u_channel_count=$(grep -c '^#EXTINF:' "$m3u_temp_file")

    [ "$m3u_channel_count" -gt 0 ] || {
        echo "M3U 没有有效频道" >&2
        rm -f "$m3u_temp_file"
        return 1
    }

    # 原子替换正式文件。
    mv "$m3u_temp_file" "$M3U_FILE" || {
        echo "无法替换 M3U 文件" >&2
        rm -f "$m3u_temp_file"
        return 1
    }

    echo "M3U 频道数量: $m3u_channel_count"
}

# ==============================================================================
# 主流程
# ==============================================================================

main() {
    echo "========================================"
    echo " cable2m3u"
    echo "========================================"

    # --------------------------------------------------------------------------
    # 初始化
    # --------------------------------------------------------------------------

    init_runtime || exit 1
    check_dependencies || exit 1
    setup_web_links || exit 1

    # --------------------------------------------------------------------------
    # NavCheck
    # --------------------------------------------------------------------------

    echo "正在执行 NavCheck..."

    api_navcheck || {
        echo "NavCheck 请求失败" >&2
        exit 1
    }

    api_check_json "$NAVCHECK_FILE" || exit 1

    # --------------------------------------------------------------------------
    # 获取 account
    # --------------------------------------------------------------------------

    account=$(api_get_account)

    [ -n "$account" ] || {
        echo "NavCheck 未返回 account" >&2
        exit 1
    }

    echo "Account: $account"

    # --------------------------------------------------------------------------
    # 获取频道
    # --------------------------------------------------------------------------

    echo "正在获取频道列表..."

    api_get_channels "$account" || {
        echo "GetGroupChannels 请求失败" >&2
        exit 1
    }

    api_check_json "$CHANNEL_FILE" || exit 1

    channel_count=$(api_check_channels) || exit 1

    echo "API 频道数量: $channel_count"

    # --------------------------------------------------------------------------
    # 标准化
    # --------------------------------------------------------------------------

    echo "正在标准化频道..."

    channel_normalize || {
        echo "频道标准化失败" >&2
        exit 1
    }

    normalized_count=$(wc -l < "$CHANNEL_DATA_FILE")

    echo "标准化频道数量: $normalized_count"

    [ "$normalized_count" -gt 0 ] || {
        echo "标准化后没有频道" >&2
        exit 1
    }

    # --------------------------------------------------------------------------
    # M3U
    # --------------------------------------------------------------------------

    generate_m3u || exit 1

    # --------------------------------------------------------------------------
    # 完成
    # --------------------------------------------------------------------------

    echo "----------------------------------------"
    echo "生成完成:"
    echo "  M3U : $M3U_FILE"
    echo "  Web : $WEB_DIR/iptv.m3u"
    echo "----------------------------------------"
}

# ==============================================================================
# END RUNTIME
# ==============================================================================

main "$@"