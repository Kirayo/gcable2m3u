# name
#   标准化后的频道名称。
#
# logo
#   API 返回的 imageUrl。
#
# sourceGroupId
#   广电 API 的 groupId。
#
# playUrls[]
#   原始播放地址列表。
#
# playUrl
#   当前选中的播放地址。
